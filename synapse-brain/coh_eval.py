"""
Coherence of generated text, measured instead of eyeballed.

20 prompts (300 bytes of held-out enwik8 test text), 400 generated bytes each. For every
continuation (and for the REAL continuation, as the human ceiling):
  words   : share of words (2+ letters) that exist in the training text (>= 5 times)
  bigrams : share of adjacent word pairs that occur in the training text (>= 2 times) - syntax
  trigrams: same for word triples - longer syntax
  topic   : share of the prompt's content words (6+ letters) that come back in the continuation
  loops   : share of repeated word 4-grams inside a continuation (lower is better)

    python3 coh_eval.py brain  <module_path> <train_MB> [temp ...]
    python3 coh_eval.py tx     <checkpoint>             [temp ...]
    python3 coh_eval.py real
Samples are cached in data/coh_<name>.npy so every model is judged on identical prompts.
"""
import importlib
import os
import re
import sys
import time
from collections import Counter

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
N_PROMPT, N_GEN, N_SAMPLES = 300, 400, int(os.environ.get("COH_N", 20))
WORD = re.compile(rb"[A-Za-z]+")


def load():
    data = np.fromfile(os.path.join(HERE, "data", "enwik8"), np.uint8)
    rng = np.random.default_rng(7)
    starts = rng.integers(95_000_000, 99_900_000, N_SAMPLES)
    prompts = [data[s : s + N_PROMPT].tobytes() for s in starts]
    real = [data[s + N_PROMPT : s + N_PROMPT + N_GEN].tobytes() for s in starts]
    return data, prompts, real


def ngram_sets(train):
    cache = os.path.join(HERE, "data", "coh_ngrams.npz")
    if os.path.exists(cache):
        z = np.load(cache, allow_pickle=True)
        return set(z["words"].tolist()), z["bi"], z["tri"]
    ws = [w.lower() for w in WORD.findall(train.tobytes())]
    ids = {}
    seq = np.fromiter((ids.setdefault(w, len(ids)) for w in ws), np.int64, len(ws))
    cnt = Counter(ws)
    words = np.array(sorted(w for w, c in cnt.items() if c >= 5 and len(w) >= 2), dtype=object)
    bi = seq[:-1] * 4_000_000 + seq[1:]
    u, c = np.unique(bi, return_counts=True)
    bi = u[c >= 2]
    tri = (seq[:-2] * 4_000_000 + seq[1:-1]) * 4_000_000 + seq[2:]
    u, c = np.unique(tri, return_counts=True)
    tri = u[c >= 2]
    np.savez(cache, words=words, bi=bi, tri=tri, vocab=np.array(list(ids), dtype=object))
    return set(words.tolist()), bi, tri


def score(prompts, conts, words, bi, tri, vocab_ids):
    r = dict(words=[], bigrams=[], trigrams=[], topic=[], loops=[])
    for p, c in zip(prompts, conts):
        ws = [w.lower() for w in WORD.findall(c)]
        r["words"].append(np.mean([w in words for w in ws if len(w) >= 2]) if ws else 0)
        ids = [vocab_ids.get(w, -1) for w in ws]
        b = [a * 4_000_000 + b_ for a, b_ in zip(ids, ids[1:]) if a >= 0 and b_ >= 0]
        r["bigrams"].append(np.isin(b, bi).sum() / max(len(ids) - 1, 1))
        t = [(a * 4_000_000 + b_) * 4_000_000 + c_ for a, b_, c_ in zip(ids, ids[1:], ids[2:])
             if a >= 0 and b_ >= 0 and c_ >= 0]
        r["trigrams"].append(np.isin(t, tri).sum() / max(len(ids) - 2, 1))
        pw = {w.lower() for w in WORD.findall(p) if len(w) >= 6}
        r["topic"].append(len(pw & set(ws)) / max(len(pw), 1))
        g = Counter(tuple(ws[i : i + 4]) for i in range(len(ws) - 3))
        r["loops"].append(sum(v for v in g.values() if v > 1) / max(len(ws) - 3, 1))
    return {k: float(np.mean(v)) for k, v in r.items()}


def main():
    data, prompts, real = load()
    words, bi, tri = ngram_sets(data[:90_000_000])
    vocab = np.load(os.path.join(HERE, "data", "coh_ngrams.npz"), allow_pickle=True)["vocab"]
    vocab_ids = {w: i for i, w in enumerate(vocab.tolist())}
    kind = sys.argv[1]
    runs = {}
    if kind == "real":
        runs["real text"] = real
    elif kind == "tx":
        import torch

        from tx_model import GPT, generate

        torch.set_num_threads(os.cpu_count())
        ck = torch.load(sys.argv[2])
        a = ck["args"]
        m = GPT(a["layers"], a["dim"], a["heads"], a["ctx"])
        m.load_state_dict(ck["state"])
        for temp in [float(x) for x in sys.argv[3:]] or [0.8]:
            runs[f"{os.path.basename(sys.argv[2])} T={temp}"] = [
                generate(m, p, N_GEN, temp=temp, seed=k) for k, p in enumerate(prompts)]
    else:
        sys.path.insert(0, os.path.dirname(os.path.abspath(sys.argv[2])))
        bm = importlib.import_module(os.path.basename(sys.argv[2])[:-3])
        n = int(float(sys.argv[3]) * 1e6)
        buf = np.zeros(n + N_SAMPLES * 4 * (N_PROMPT + N_GEN + 100) + 10, np.uint8)
        buf[:n] = data[:n]
        st = bm.make_state(0, len(buf))
        snap = os.path.join(HERE, "data", f"_brain_{sys.argv[3]}MB.npz")  # trained brain, reused
        if os.path.exists(snap) and os.environ.get("COH_REUSE"):
            z = np.load(snap)
            for k in st:
                st[k][...] = z[k]
        else:
            t = time.perf_counter()
            bm.process(buf, st, 0, n, n, n)
            print(f"trained on {n / 1e6:.0f} MB in {time.perf_counter() - t:.0f}s", flush=True)
            if os.environ.get("COH_REUSE"):
                np.savez(snap, **st)
        saved = {k: v.copy() for k, v in st.items() if k != "T"}
        np.save(snap + ".T.npy", st["T"])
        for spec in sys.argv[4:] or ["0.8"]:
            temp, recall = (float(v) for v in (spec.split(":") + ["1.0"])[:2])
            out, pos = [], n
            for k, p in enumerate(prompts):
                out.append(bm.generate(st, buf, pos, N_GEN, temp=temp, seed=k, prompt=p, recall=recall))
                pos += N_PROMPT + N_GEN + 100
            runs[f"{os.path.basename(sys.argv[2])}@{sys.argv[3]}MB T={temp} recall={recall}"] = out
            st["T"][:] = np.load(snap + ".T.npy", mmap_mode="r")  # every setting starts from the same brain
            for k, v in saved.items():
                st[k][...] = v
        os.remove(snap + ".T.npy")
    for name, conts in runs.items():
        s = score(prompts, conts, words, bi, tri, vocab_ids)
        line = f"{name:<40}" + "".join(f"{k} {v * 100:5.1f}%  " for k, v in s.items())
        print(line, flush=True)
        with open(os.path.join(HERE, "data", "coh_results.txt"), "a") as f:
            f.write(line + "\n")
        safe = re.sub(r"[^A-Za-z0-9_.=@-]", "_", name)
        np.save(os.path.join(HERE, "data", f"coh_{safe}.npy"), np.array(conts, dtype=object))


if __name__ == "__main__":
    main()

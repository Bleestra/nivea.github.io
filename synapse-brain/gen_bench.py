"""
Text generation: SynapseBrain-LM (trained on 90 MB of enwik8) vs the transformers.

Same 10 prompts (200 bytes taken from the held-out test text), 800 generated bytes each.
  real-word rate : share of generated words (2+ letters) that occur >= 5 times in training text
  copied         : share of generated bytes covered by a 32-byte window that appears verbatim in
                   the training text (memorised / plagiarised text)
  repeats        : share of word 4-grams that repeat inside the same sample (loops)
  speed          : generated bytes per second (batch 1)
"""
import os
import re
import time
from collections import Counter

import numpy as np
import torch
from numba import njit

from brain_lm import generate as brain_generate, make_state, process
from tx_model import GPT, generate as tx_generate

HERE = os.path.dirname(os.path.abspath(__file__))
TRAIN, W = 90_000_000, 32
torch.set_num_threads(os.cpu_count())


@njit(cache=True)
def window_hashes(a, w):
    n = len(a) - w + 1
    out = np.empty(max(n, 0), np.uint64)
    B = np.uint64(1099511628211)
    Bw = np.uint64(1)
    for _ in range(w):
        Bw = Bw * B
    h = np.uint64(0)
    for i in range(len(a)):
        h = h * B + np.uint64(a[i]) + np.uint64(1)
        if i >= w:
            h = h - (np.uint64(a[i - w]) + np.uint64(1)) * Bw
        if i >= w - 1:
            out[i - w + 1] = h
    return out


def metrics(texts, vocab, train_hashes):
    words = [w.lower() for t in texts for w in re.findall(rb"[A-Za-z]{2,}", t)]
    real = np.mean([w in vocab for w in words]) if words else 0.0
    cov, tot, rep4, n4 = 0, 0, 0, 0
    for t in texts:
        a = np.frombuffer(t, np.uint8)
        hit = np.zeros(len(a), bool)
        if len(a) >= W:
            h = window_hashes(a, W)
            idx = np.searchsorted(train_hashes, h)
            idx[idx >= len(train_hashes)] = 0
            for i in np.nonzero(train_hashes[idx] == h)[0]:
                hit[i : i + W] = True
        cov += hit.sum()
        tot += len(a)
        ws = re.findall(rb"[A-Za-z]+", t)
        grams = [tuple(ws[i : i + 4]) for i in range(len(ws) - 3)]
        c = Counter(grams)
        rep4 += sum(v for v in c.values() if v > 1)
        n4 += len(grams)
    return real, cov / tot, rep4 / max(n4, 1)


def main():
    data = np.fromfile(os.path.join(HERE, "data", "enwik8"), np.uint8)
    train = data[:TRAIN]
    t = time.perf_counter()
    counts = Counter(w.lower() for w in re.findall(rb"[A-Za-z]{2,}", train.tobytes()))
    vocab = {w for w, c in counts.items() if c >= 5}
    train_hashes = np.sort(window_hashes(train, W))
    print(f"vocab {len(vocab):,} words, {len(train_hashes):,} training windows ({time.perf_counter() - t:.0f}s)")

    rng = np.random.default_rng(0)
    starts = rng.integers(95_000_000, 99_990_000, 10)
    prompts = [data[s : s + 200].tobytes() for s in starts]
    N = 800
    samples = {}

    # SynapseBrain: learn 90 MB once, then speak (weights frozen, working memory on)
    buf = np.zeros(TRAIN + 20 * 2000, np.uint8)
    buf[:TRAIN] = train
    st = make_state(0, len(buf))
    process(buf, st, 0, TRAIN, TRAIN, TRAIN)
    for temp in (0.8, 1.0):
        out, pos, t = [], TRAIN, time.perf_counter()
        gen_t = 0.0
        for k, p in enumerate(prompts):
            t1 = time.perf_counter()
            out.append(brain_generate(st, buf, pos, N, temp=temp, seed=k, prompt=p))
            gen_t += time.perf_counter() - t1
            pos += len(p) + N + 100
        samples[f"SynapseBrain T={temp}"] = (out, len(prompts) * N / gen_t)
    del st

    for name in ["transformer_10x.pt", "transformer.pt"]:
        ck = torch.load(os.path.join(HERE, "data", name))
        a = ck["args"]
        m = GPT(a["layers"], a["dim"], a["heads"], a["ctx"])
        m.load_state_dict(ck["state"])
        for temp in (0.8, 1.0):
            t = time.perf_counter()
            out = [tx_generate(m, p, N, temp=temp, seed=k) for k, p in enumerate(prompts)]
            samples[f"{name[:-3]} T={temp}"] = (out, len(prompts) * N / (time.perf_counter() - t))

    print(f"\n{'model':<28}{'real words':>11}{'copied':>9}{'repeats':>9}{'bytes/s':>10}")
    for name, (texts, speed) in samples.items():
        r, c, rp = metrics(texts, vocab, train_hashes)
        print(f"{name:<28}{r * 100:10.1f}%{c * 100:8.1f}%{rp * 100:8.1f}%{speed:10.0f}")
    with open(os.path.join(HERE, "samples.md"), "w") as f:
        f.write("# Generated samples (800 bytes after a 200-byte prompt from the enwik8 test text)\n\n")
        for k in range(3):
            f.write(f"## Prompt {k + 1}\n\n```\n{prompts[k].decode('utf8', 'replace')}\n```\n\n")
            for name, (texts, _) in samples.items():
                if name.endswith("0.8"):
                    f.write(f"**{name}**\n\n```\n{texts[k].decode('utf8', 'replace')}\n```\n\n")


if __name__ == "__main__":
    main()

export const DECK_RULES = { colossi: 3, gates: 3, abilities: 24, maxCopies: 2, maxAspects: 2 };

// §04: 3 different colossi of at most two base aspects; 3 different gates (any aspects);
// 24 abilities of those aspects or neutral, at most two copies of one id.
export function validateDeck(deck) {
  const errors = [];
  const colossi = deck?.colossi ?? [], gates = deck?.gates ?? [], abilities = deck?.abilities ?? [];
  if (colossi.length !== DECK_RULES.colossi) errors.push(`нужно ровно ${DECK_RULES.colossi} колосса`);
  if (new Set(colossi).size !== colossi.length) errors.push('колоссы должны различаться');
  for (const id of colossi) if (!COLOSSI[id]) errors.push(`неизвестный колосс ${id}`);
  const aspects = new Set(colossi.filter(id => COLOSSI[id]).map(id => COLOSSI[id].aspect));
  if (aspects.size > DECK_RULES.maxAspects) errors.push('в составе больше двух базовых аспектов');
  if (gates.length !== DECK_RULES.gates) errors.push(`нужно ровно ${DECK_RULES.gates} ворот`);
  if (new Set(gates).size !== gates.length) errors.push('ворота должны различаться');
  for (const id of gates) if (!GATES[id]) errors.push(`неизвестные ворота ${id}`);
  if (abilities.length !== DECK_RULES.abilities) errors.push(`нужно ровно ${DECK_RULES.abilities} способности`);
  const copies = {};
  for (const id of abilities) {
    const a = ABILITIES[id];
    if (!a) { errors.push(`неизвестная способность ${id}`); continue; }
    copies[id] = (copies[id] ?? 0) + 1;
    if (a.aspect !== 'neutral' && !aspects.has(a.aspect)) errors.push(`${a.name}: аспект не входит в состав`);
  }
  for (const [id, n] of Object.entries(copies)) {
    if (n > DECK_RULES.maxCopies) errors.push(`${ABILITIES[id].name}: больше ${DECK_RULES.maxCopies} копий`);
  }
  return [...new Set(errors)];
}

